package com.notebookrag.ingestion;

import java.io.File;
import java.io.IOException;

/**
 * Интерфейс для парсинга документов различных форматов.
 *
 * Каждый парсер отвечает за извлечение текстового содержимого
 * из конкретного формата файла (TXT, PDF, DOCX).
 *
 * Важно для RAG: качество извлеченного текста напрямую влияет
 * на качество поиска и ответов. Парсер должен сохранять структуру
 * текста (параграфы, переносы строк) где это возможно.
 */
public interface DocumentParser {

    /**
     * Извлекает текстовое содержимое из файла.
     *
     * @param file файл для парсинга
     * @return извлеченный текст
     * @throws IOException если произошла ошибка чтения файла
     */
    String parse(File file) throws IOException;
}
